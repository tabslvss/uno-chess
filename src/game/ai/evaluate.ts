export function squareValue(piece: `${Side}${PieceType}`, sq: number): number {
  const t = typeOf(piece);
  const s = sideOf(piece);
  const idx = s === 'w' ? sq : (7 - sqRank(sq)) * 8 + sqFile(sq);
  return PIECE_VALUE[t] + PST[t][idx]!;
}

/** Static evaluation in centipawns from `side`'s point of view. */
export function evaluate(board: Board, side: Side): number {
  let score = 0;
  for (let sq = 0; sq < 64; sq++) {
    const p = board[sq];
    if (!p) continue;
    const v = squareValue(p, sq);
    score += sideOf(p) === side ? v : -v;
  }
  return score;
}
